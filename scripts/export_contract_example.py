#!/usr/bin/env python3
"""Write docs/contract-example.json: a REAL /api/v1/sky-patch response.

It goes through the actual API (FastAPI TestClient) on a cached Golden Path
file, so the example is exactly what the frontend receives, with image URLs
under --base (default http://localhost:8000). Anomaly spectra are trimmed to 3
channels to keep the file readable; everything else is untouched.

    python scripts/export_contract_example.py [--target WISE_0855] [--base http://localhost:8000]
"""

import argparse
import json
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))
os.environ.setdefault("LIVE_WARMUP", "0")


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--target", default="WISE_0855")
    p.add_argument("--base", default="http://localhost:8000")
    p.add_argument("--out", type=Path, default=REPO_ROOT / "docs" / "contract-example.json")
    args = p.parse_args()

    from fastapi.testclient import TestClient

    from app.main import app

    with TestClient(app, base_url=args.base) as client:
        res = client.get("/api/v1/sky-patch", params={"target": args.target, "band": "H2O"})
        res.raise_for_status()
        body = res.json()
        # Other real responses the frontend must handle (not part of SkyPatchResponse).
        others = {}
        lost = client.get("/api/v1/jobs/00000000-0000-4000-8000-000000000000")
        others["GET /api/v1/jobs/{lost job_id} -> 404"] = lost.json()
        others["GET /credits -> 200"] = client.get("/credits").json()
    trimmed = 0
    for a in body["difference_imaging"]["detected_anomalies"]:
        if len(a["spectrum_102_bands"]) > 3:
            trimmed += len(a["spectrum_102_bands"]) - 3
            a["spectrum_102_bands"] = a["spectrum_102_bands"][:3]
    body = {"_comment": f"Real GET /api/v1/sky-patch?target={args.target}&band=H2O response "
                        f"(anomaly spectra trimmed to 3 channels; {trimmed} channels omitted). "
                        "Generated by scripts/export_contract_example.py. `_other_examples` holds other "
                        "real responses (not part of the sky-patch body).", **body,
            "_other_examples": others}
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(body, indent=2, ensure_ascii=False) + "\n", "utf-8")
    print(f"Wrote {args.out.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
